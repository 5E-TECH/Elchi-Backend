import { randomUUID } from 'node:crypto';
import { DataSource } from 'typeorm';
import { TruncFractionalExtraCostApprovals1716000000205 } from '../../../../migrations/1716000000205-TruncFractionalExtraCostApprovals';

/**
 * iMNLvs06 — migratsiya 205 haqiqiy Postgres'da
 * (LOGISTICS_POST_LIST_PG_TEST_URI — faqat lokal *_test baza; bo'lmasa skip).
 * O'z vaqtinchalik bazasini yaratadi va oxirida o'chiradi.
 *
 *  • kasrli pending so'rov — summa va operation_payload.extraCost butun;
 *  • butun summali, yakunlangan va o'chirilgan so'rovlar — tegilmaydi;
 *  • qayta yurgizish hech narsani o'zgartirmaydi;
 *  • jadval yo'q — xatosiz, hech narsa qilmaydi.
 */
const uri = process.env.LOGISTICS_POST_LIST_PG_TEST_URI;
const localTestDatabase = (() => {
  if (!uri) return false;
  const url = new URL(uri);
  return (
    ['127.0.0.1', 'localhost'].includes(url.hostname) &&
    url.pathname.endsWith('_test')
  );
})();

(localTestDatabase ? describe : describe.skip)(
  'migratsiya 205 — kasrli qo`shimcha xarajat so`rovlari (haqiqiy Postgres)',
  () => {
    const dbName = `spec_xc_trunc_${randomUUID().replace(/-/g, '').slice(0, 12)}`;
    let admin: DataSource;
    let db: DataSource;
    const migration = new TruncFractionalExtraCostApprovals1716000000205();

    /** TypeORM kabi: bitta tranzaksiyada. */
    const runUp = async () => {
      const runner = db.createQueryRunner();
      await runner.connect();
      await runner.startTransaction();
      try {
        await migration.up(runner);
        await runner.commitTransaction();
      } catch (error) {
        await runner.rollbackTransaction();
        throw error;
      } finally {
        await runner.release();
      }
    };

    const insertApproval = async (row: {
      amount: string;
      payload: Record<string, unknown>;
      status?: string;
      is_deleted?: boolean;
    }): Promise<string> => {
      const [saved]: Array<{ id: string }> = await db.query(
        `INSERT INTO "order_schema"."order_extra_cost_approvals"
           ("order_id", "market_id", "requested_by_user_id", "action", "amount",
            "operation_payload", "status", "is_deleted")
         VALUES (1, 2, 3, 'sell', $1, $2, $3, $4) RETURNING "id"::text AS "id"`,
        [
          row.amount,
          JSON.stringify(row.payload),
          row.status ?? 'pending',
          row.is_deleted ?? false,
        ],
      );
      return saved.id;
    };

    const read = async (
      id: string,
    ): Promise<{ amount: string; payload: Record<string, unknown> }> => {
      const [row]: Array<{
        amount: string;
        operation_payload: Record<string, unknown>;
      }> = await db.query(
        `SELECT "amount"::text AS "amount", "operation_payload"
           FROM "order_schema"."order_extra_cost_approvals" WHERE "id" = $1`,
        [id],
      );
      return { amount: row.amount, payload: row.operation_payload };
    };

    beforeAll(async () => {
      admin = new DataSource({ type: 'postgres', url: uri });
      await admin.initialize();
      await admin.query(`CREATE DATABASE "${dbName}"`);
      const url = new URL(uri as string);
      url.pathname = `/${dbName}`;
      db = new DataSource({ type: 'postgres', url: url.toString() });
      await db.initialize();
    }, 60_000);

    afterAll(async () => {
      if (db?.isInitialized) await db.destroy();
      if (admin?.isInitialized) {
        await admin.query(`DROP DATABASE IF EXISTS "${dbName}" WITH (FORCE)`);
        await admin.destroy();
      }
    });

    it('jadval yo`q — xatosiz, hech narsa qilmaydi', async () => {
      await expect(runUp()).resolves.toBeUndefined();
    });

    describe('jadval bor', () => {
      beforeAll(async () => {
        // 1716000000026 dagi shakl (migratsiya o'qiydigan ustunlar).
        await db.query(`CREATE SCHEMA "order_schema"`);
        await db.query(`
          CREATE TABLE "order_schema"."order_extra_cost_approvals" (
            "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
            "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
            "is_deleted" boolean NOT NULL DEFAULT false,
            "order_id" bigint NOT NULL,
            "market_id" bigint NOT NULL,
            "requested_by_user_id" bigint NOT NULL,
            "action" character varying(20) NOT NULL,
            "amount" numeric(14,2) NOT NULL DEFAULT 0,
            "operation_payload" jsonb NOT NULL,
            "status" character varying(20) NOT NULL DEFAULT 'pending'
          )
        `);
      });

      beforeEach(async () => {
        await db.query(
          `TRUNCATE "order_schema"."order_extra_cost_approvals" RESTART IDENTITY`,
        );
      });

      it('kasrli pending so`rov — summa va payload butun; qayta yurgizish xavfsiz', async () => {
        const id = await insertApproval({
          amount: '1500.50',
          payload: { comment: 'x', extraCost: 1500.5, proofFileKeys: [] },
        });
        await runUp();
        expect(await read(id)).toEqual({
          amount: '1500.00',
          payload: { comment: 'x', extraCost: 1500, proofFileKeys: [] },
        });
        await runUp();
        expect((await read(id)).amount).toBe('1500.00');
      });

      it('butun summali, yakunlangan va o`chirilgan so`rovlar tegilmaydi', async () => {
        const whole = await insertApproval({
          amount: '5000.00',
          payload: { extraCost: 5000 },
        });
        const approved = await insertApproval({
          amount: '700.25',
          payload: { extraCost: 700.25 },
          status: 'approved',
        });
        const rejected = await insertApproval({
          amount: '800.75',
          payload: { extraCost: 800.75 },
          status: 'rejected',
        });
        const deleted = await insertApproval({
          amount: '900.50',
          payload: { extraCost: 900.5 },
          is_deleted: true,
        });
        await runUp();
        expect(await read(whole)).toEqual({
          amount: '5000.00',
          payload: { extraCost: 5000 },
        });
        expect(await read(approved)).toEqual({
          amount: '700.25',
          payload: { extraCost: 700.25 },
        });
        expect((await read(rejected)).amount).toBe('800.75');
        expect((await read(deleted)).amount).toBe('900.50');
      });

      it('payload`da extraCost raqam bo`lmasa — faqat summa kesiladi', async () => {
        const id = await insertApproval({
          amount: '1200.40',
          payload: { comment: 'eski' },
        });
        await runUp();
        expect(await read(id)).toEqual({
          amount: '1200.00',
          payload: { comment: 'eski' },
        });
      });
    });
  },
);
